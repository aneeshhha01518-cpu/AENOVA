@app.post("/api/feedback")
def save_feedback(
    request: FeedbackRequest
):

    try:

        feedback_type = clean_text(
            request.feedback_type
        ).lower()

        if feedback_type not in {
            "like",
            "dislike"
        }:

            return {
                "success": False,
                "message": (
                    "feedback_type must be like or dislike."
                )
            }

        profile_id = request.profile_id

        if profile_id is None:

            try:

                session = (
                    supabase
                    .table("chat_sessions")
                    .select("profile_id")
                    .eq(
                        "session_key",
                        clean_text(
                            request.session_id
                        )
                    )
                    .limit(1)
                    .execute()
                )

                if session.data:

                    profile_id = (
                        session.data[0]
                        .get("profile_id")
                    )

            except Exception:
                pass

        data = {
            "feedback_type": feedback_type
        }

        if profile_id is not None:

            data["profile_id"] = profile_id

        if request.opportunity_id is not None:

            data["opportunity_id"] = (
                request.opportunity_id
            )

        result = (
            supabase
            .table("feedback")
            .insert(data)
            .execute()
        )

        return {
            "success": True,
            "message": "Feedback saved.",
            "data": result.data
        }

    except Exception as error:

        print(
            "Feedback save error:",
            error
        )

        return {
            "success": False,
            "message": str(error)
        }


