# GROQ AI CALL
# ============================================================

def ask_groq(
    history,
    current_message
):

    messages = [
        {
            "role": "system",
            "content": ANEBESTRA_SYSTEM_INSTRUCTION
        }
    ]

    messages.extend(history)

    messages.append(
        {
            "role": "user",
            "content": current_message
        }
    )

    payload = {
        "model": GROQ_MODEL,
        "messages": messages,
        "temperature": 0.4,
        "max_tokens": 1200
    }

    headers = {
        "Authorization": (
            f"Bearer {GROQ_API_KEY}"
        ),
        "Content-Type": "application/json"
    }

    response = requests.post(
        GROQ_URL,
        headers=headers,
        json=payload,
        timeout=GROQ_TIMEOUT
    )

    if not response.ok:

        print(
            "Groq API error:",
            response.status_code,
            response.text[:1000]
        )

        raise RuntimeError(
            f"Groq API returned "
            f"{response.status_code}"
        )

    data = response.json()

    choices = data.get(
        "choices",
        []
    )

    if not choices:

        raise RuntimeError(
            "Groq returned no response."
        )

    reply = clean_text(
        choices[0]
        .get("message", {})
        .get("content")
    )

    if not reply:

        raise RuntimeError(
            "Groq returned an empty response."
        )

    return reply


