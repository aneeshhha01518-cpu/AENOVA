# OPPORTUNITY RELEVANCE
# ============================================================

def find_relevant_opportunities(
    message,
    opportunities,
    limit=8
):

    text = message.lower()

    if not opportunities:
        return []

    scored = []

    question_words = set(
        re.findall(
            r"[a-zA-Z0-9+#.-]{3,}",
            text
        )
    )

    for opportunity in opportunities:

        title = clean_text(
            opportunity.get("title")
        )

        description = clean_text(
            opportunity.get("description")
        )

        category = clean_text(
            opportunity.get("category")
        )

        organization = clean_text(
            opportunity.get("organization")
        )

        skills = clean_text(
            opportunity.get("skills_required")
        )

        combined = " ".join(
            [
                title,
                description,
                category,
                organization,
                skills
            ]
        ).lower()

        score = 0

        if any(
            word in text
            for word in [
                "hackathon",
                "hackathons",
                "internship",
                "internships",
                "competition",
                "competitions",
                "workshop",
                "workshops",
                "event",
                "events",
                "opportunity",
                "opportunities",
                "contest",
                "challenge"
            ]
        ):

            score += 1

        for word in question_words:

            if word in combined:
                score += 2

        if (
            "hackathon" in text
            and "hackathon" in category.lower()
        ):

            score += 5

        if (
            "internship" in text
            and "internship" in category.lower()
        ):

            score += 5

        if (
            "workshop" in text
            and "workshop" in category.lower()
        ):

            score += 5

        if (
            "competition" in text
            and "competition" in category.lower()
        ):

            score += 5

        if score > 0:

            scored.append(
                (
                    score,
                    opportunity
                )
            )

    scored.sort(
        key=lambda item: item[0],
        reverse=True
    )

    selected = [
        opportunity
        for _, opportunity in scored[:limit]
    ]

    if (
        not selected
        and looks_like_opportunity_request(message)
    ):

        return opportunities[:limit]

    return selected


