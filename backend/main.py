def clean_text(value):

    if value is None:
        return ""

    return str(value).strip()


def is_greeting(message: str) -> bool:

    text = message.lower().strip()

    greetings = {
        "hi",
        "hii",
        "hiii",
        "hello",
        "hey",
        "heyy",
        "hey there",
        "good morning",
        "good afternoon",
        "good evening",
        "gm",
    }

    return text in greetings


def is_thanks(message: str) -> bool:

    text = message.lower().strip()

    patterns = [
        "thank you",
        "thanks",
        "thank u",
        "thx",
        "thanks a lot",
    ]

    return text in patterns


def is_goodbye(message: str) -> bool:

    text = message.lower().strip()

    patterns = [
        "bye",
        "goodbye",
        "see you",
        "see ya",
        "good night",
    ]

    return text in patterns


def looks_like_opportunity_request(message: str) -> bool:

    text = message.lower()

    keywords = [
        "hackathon",
        "hackathons",
        "internship",
        "internships",
        "competition",
        "competitions",
        "workshop",
        "workshops",
        "event",
        "events",
        "opportunit",
        "contest",
        "challenge",
        "challenges",
        "registration",
        "deadline",
        "apply",
        "application",
    ]

    return any(
        keyword in text
        for keyword in keywords
    )


