# CHAT SESSION DATABASE
# ============================================================

def get_or_create_session(
    session_key: str,
    profile_id: Optional[int] = None
):

    session_key = clean_text(
        session_key
    )

    if not session_key:

        session_key = "default"

    try:

        existing = (
            supabase
            .table("chat_sessions")
            .select("*")
            .eq("session_key", session_key)
            .limit(1)
            .execute()
        )

        if existing.data:

            return existing.data[0]

        data = {
            "session_key": session_key
        }

        if profile_id is not None:

            data["profile_id"] = profile_id

        result = (
            supabase
            .table("chat_sessions")
            .insert(data)
            .execute()
        )

        if result.data:

            return result.data[0]

    except Exception as error:

        print(
            "Session creation error:",
            error
        )

        # Handle a race where another request created
        # the same unique session_key.

        try:

            existing = (
                supabase
                .table("chat_sessions")
                .select("*")
                .eq(
                    "session_key",
                    session_key
                )
                .limit(1)
                .execute()
            )

            if existing.data:

                return existing.data[0]

        except Exception as retry_error:

            print(
                "Session retry error:",
                retry_error
            )

        raise

    raise RuntimeError(
        "Unable to create chat session."
    )


# ============================================================
# LOAD CHAT HISTORY
# ============================================================

def load_chat_history(
    session_id: int
):

    try:

        result = (
            supabase
            .table("chat_messages")
            .select("role,message,created_at")
            .eq(
                "session_id",
                session_id
            )
            .order(
                "created_at",
                desc=False
            )
            .limit(MAX_HISTORY_MESSAGES)
            .execute()
        )

        history = []

        for item in result.data or []:

            role = item.get("role")

            message = clean_text(
                item.get("message")
            )

            if role in {
                "user",
                "assistant"
            } and message:

                history.append(
                    {
                        "role": role,
                        "content": message
                    }
                )

        return history

    except Exception as error:

        print(
            "Chat history error:",
            error
        )

        return []


# ============================================================
# SAVE CHAT MESSAGE
# ============================================================

def save_chat_message(
    session_id: int,
    role: str,
    message: str
):

    role = clean_text(role)

    message = clean_text(message)

    if role not in {
        "user",
        "assistant"
    }:

        raise ValueError(
            "Invalid chat message role."
        )

    if not message:
        return

    (
        supabase
        .table("chat_messages")
        .insert(
            {
                "session_id": session_id,
                "role": role,
                "message": message
            }
        )
        .execute()
    )


