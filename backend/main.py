@app.get("/api/chat/history/{session_key}")
def chat_history(
    session_key: str
):

    try:

        session = (
            supabase
            .table("chat_sessions")
            .select("id")
            .eq(
                "session_key",
                clean_text(session_key)
            )
            .limit(1)
            .execute()
        )

        if not session.data:

            return {
                "success": True,
                "messages": []
            }

        session_id = session.data[0]["id"]

        result = (
            supabase
            .table("chat_messages")
            .select(
                "id,role,message,created_at"
            )
            .eq(
                "session_id",
                session_id
            )
            .order(
                "created_at",
                desc=False
            )
            .execute()
        )

        return {
            "success": True,
            "messages": result.data or []
        }

    except Exception as error:

        return {
            "success": False,
            "message": str(error),
            "messages": []
        }


